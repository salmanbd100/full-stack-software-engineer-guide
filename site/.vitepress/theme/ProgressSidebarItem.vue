<script setup lang="ts">
/**
 * VitePress 1.6.4's VPSidebarItem.vue, with a "read it" checkbox beside every chapter link.
 * config.ts aliases every import of VPSidebarItem.vue to this file, VitePress's documented
 * way to override an internal component.
 *
 * 🔴 Internal components can change in any VitePress release. On every upgrade, diff this file
 * against node_modules/vitepress/dist/client/theme-default/components/VPSidebarItem.vue and
 * carry the changes over. Everything but the checkbox, its imports and its styles is theirs.
 */
import type { DefaultTheme } from 'vitepress/theme'
import { useData } from 'vitepress'
import { computed } from 'vue'
import { useSidebarControl } from 'vitepress/dist/client/theme-default/composables/sidebar.js'
import VPLink from 'vitepress/dist/client/theme-default/components/VPLink.vue'
import { progress, slugOf, toggle as toggleRead } from './progress'

const props = defineProps<{
  item: DefaultTheme.SidebarItem
  depth: number
}>()

const {
  collapsed,
  collapsible,
  isLink,
  isActiveLink,
  hasActiveLink,
  hasChildren,
  toggle
} = useSidebarControl(computed(() => props.item))

const sectionTag = computed(() => (hasChildren.value ? 'section' : `div`))

const linkTag = computed(() => (isLink.value ? 'a' : 'div'))

const textTag = computed(() => {
  return !hasChildren.value
    ? 'p'
    : props.depth + 2 === 7
      ? 'p'
      : `h${props.depth + 2}`
})

const itemRole = computed(() => (isLink.value ? undefined : 'button'))

const classes = computed(() => [
  [`level-${props.depth}`],
  { collapsible: collapsible.value },
  { collapsed: collapsed.value },
  { 'is-link': isLink.value },
  { 'is-active': isActiveLink.value },
  { 'has-active': hasActiveLink.value }
])

function onItemInteraction(e: MouseEvent | Event) {
  if ('key' in e && e.key !== 'Enter') {
    return
  }
  !props.item.link && toggle()
}

const { localeIndex } = useData()

const isDone = computed(
  () => !!props.item.link && progress.done.has(slugOf(props.item.link))
)

const checkLabel = computed(() => {
  const title = (props.item.text ?? '').replace(/<[^>]*>/g, '').replace(/`/g, '')
  return localeIndex.value === 'bn'
    ? `“${title}” পড়া হয়েছে বলে চিহ্নিত করুন`
    : `Mark “${title}” as read`
})

// The box is uncontrolled between the click and the server's answer, so it is put back in
// line with the store afterwards — a refused tick would otherwise stay drawn as ticked.
async function onCheck(event: Event) {
  await toggleRead(props.item.link!)
  ;(event.target as HTMLInputElement).checked = isDone.value
}

function onCaretClick() {
  props.item.link && toggle()
}
</script>

<template>
  <component :is="sectionTag" class="VPSidebarItem" :class="classes">
    <div
      v-if="item.text"
      class="item"
      :role="itemRole"
      v-on="
        item.items
          ? { click: onItemInteraction, keydown: onItemInteraction }
          : {}
      "
      :tabindex="item.items && 0"
    >
      <div class="indicator" />

      <input
        v-if="item.link && progress.profile"
        type="checkbox"
        class="progress-check"
        :checked="isDone"
        :aria-label="checkLabel"
        :title="checkLabel"
        @click.stop
        @change="onCheck"
      />

      <VPLink
        v-if="item.link"
        :tag="linkTag"
        class="link"
        :href="item.link"
        :rel="item.rel"
        :target="item.target"
      >
        <component :is="textTag" class="text" v-html="item.text" />
      </VPLink>
      <component v-else :is="textTag" class="text" v-html="item.text" />

      <div
        v-if="item.collapsed != null && item.items && item.items.length"
        class="caret"
        role="button"
        aria-label="toggle section"
        @click="onCaretClick"
        @keydown.enter="onCaretClick"
        tabindex="0"
      >
        <span class="vpi-chevron-right caret-icon" />
      </div>
    </div>

    <div v-if="item.items && item.items.length" class="items">
      <template v-if="depth < 5">
        <ProgressSidebarItem
          v-for="i in item.items"
          :key="i.text"
          :item="i"
          :depth="depth + 1"
        />
      </template>
    </div>
  </component>
</template>

